export function assertTable(table: string): TableName {
  if (Object.prototype.hasOwnProperty.call(tableColumns, table)) {
    return table as TableName;
  }

  throw new Error(`Unsupported table: ${table}`);
}

const columnSets = new Map<string, ReadonlySet<string>>(
  Object.entries(tableColumns).map(([table, columns]) => [table, new Set<string>(columns)]),
);

export function assertColumns(table: TableName, columns: string[]) {
  const allowedColumns = columnSets.get(table)!;
  for (const column of columns) {
    if (!allowedColumns.has(column)) {
      throw new Error(`Unsupported column for ${table}: ${column}`);
    }
  }
}
